const { makeDb, as, sql } = require('../harness/env');
const path = require('path');
let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log('FAIL', m); } else console.log('ok  ', m); };
async function err(p, m) { try { await p; ok(false, m + ' (expected error)'); } catch (e) { ok(true, m + ' -> ' + e.message); } }
(async () => {
  const db = await makeDb(path.join(__dirname, 'migration.sql'));
  const id = n => '00000000-0000-0000-0000-' + String(n).padStart(12, '0');
  const [A, B, C, D, ADM] = [1, 2, 3, 4, 9].map(id);
  for (const u of [A, B, C, D, ADM]) await sql(db, 'insert into auth.users values ($1)', [u]);
  await sql(db, 'insert into private.admins values ($1)', [ADM]);
  const prof = async (u, g) => {
    await as(db, u, "insert into public.profiles(id,nickname,gender,region) values ($1,'nick','" + g + "','seoul')", [u]);
    await as(db, u, "insert into public.preferences(user_id,genders) values ($1,$2)", [u, g === 'man' ? ['woman'] : ['man']]);
    await as(db, u, "select public.set_birth_date('1995-01-01')");
  };
  await prof(A, 'man'); await prof(B, 'woman'); await prof(C, 'woman'); await prof(D, 'woman');
  ok((await as(db, A, 'select * from public.member_status')).rows[0].status === 'draft', 'status auto draft');
  await err(as(db, A, "update public.member_status set status='active'"), 'self status update');
  ok((await as(db, A, 'select * from public.profiles')).rows.length === 1, 'only own profile');
  ok((await as(db, A, 'select * from public.preferences')).rows.length === 1, 'only own prefs');
  await err(as(db, A, 'select * from private.user_private'), 'private schema');
  await err(as(db, A, "select public.set_birth_date('2015-01-01')"), 'under 19');
  await err(as(db, A, `select public.admin_set_status('${A}','active',true)`), 'non-admin');
  await err(as(db, null, 'select * from public.profiles'), 'anon table');
  await err(as(db, null, 'select public.get_candidates()'), 'anon func');
  await err(as(db, A, 'select * from public.get_candidates()'), 'ineligible candidates');
  await err(as(db, A, `insert into public.swipes(from_id,to_id,action) values ('${A}','${B}','like')`), 'direct swipe');
  await err(as(db, A, `insert into public.profiles(id,nickname,gender,region) values ('${B}','xx','man','x')`), 'insert other profile');
  for (const u of [A, B, C]) await as(db, ADM, `select public.admin_set_status('${u}','active',true)`);
  let r = (await as(db, A, 'select * from public.get_candidates()')).rows;
  ok(r.length === 2 && r[0].age >= 30, 'A sees B,C ' + JSON.stringify(r));
  ok((await as(db, A, `select public.swipe('${B}','like') m`)).rows[0].m === null, 'like no match');
  const m = (await as(db, B, `select public.swipe('${A}','like') m`)).rows[0].m;
  ok(m, 'mutual match');
  ok((await as(db, A, `select public.swipe('${B}','like') m`)).rows[0].m === m, 'same match');
  ok((await sql(db, 'select count(*)::int n from public.matches')).rows[0].n === 1, 'one match');
  await as(db, A, `select public.swipe('${C}','pass')`);
  ok((await as(db, A, 'select * from public.get_candidates()')).rows.length === 0, 'liked/passed excluded');
  await sql(db, "update public.swipes set created_at = now() - interval '31 days' where to_id=$1", [C]);
  ok((await as(db, A, 'select * from public.get_candidates()')).rows.length === 1, 'old pass reappears');
  await err(as(db, A, `select public.swipe('${D}','like')`), 'target ineligible');
  await err(as(db, A, `select public.swipe('${A}','like')`), 'self swipe');
  const msg = (await as(db, A, `select public.send_message('${m}','hi') x`)).rows[0].x;
  ok(msg, 'message sent');
  await err(as(db, C, `select public.send_message('${m}','hi')`), 'non party msg');
  ok((await as(db, C, 'select * from public.messages')).rows.length === 0, 'C cannot read msgs');
  ok((await as(db, B, 'select * from public.messages')).rows.length === 1, 'B reads msgs');
  await as(db, B, `select public.block_user('${A}')`);
  ok((await sql(db, 'select ended_at from public.matches')).rows[0].ended_at, 'match ended');
  await err(as(db, A, `select public.send_message('${m}','hi')`), 'msg after block');
  ok((await as(db, A, 'select * from public.blocks')).rows.length === 0, 'A no see B block');
  await as(db, A, 'select public.delete_my_account()');
  ok((await sql(db, `select (select count(*) from public.profiles where id='${A}') + (select count(*) from public.matches) + (select count(*) from private.user_private where user_id='${A}') n`)).rows[0].n == 0, 'cascade delete');
  console.log(fails ? fails + ' FAILS' : 'ALL OK');
})().catch(e => { console.error(e); process.exit(1); });
